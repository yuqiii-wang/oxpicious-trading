/**
 * Security classification tab — the database/sec_statics/ JSON tree,
 * loaded as a NESTED DIRECTORY TABLE: one expandable row per real
 * directory path ("sec_classification/indices/CONS"), file rows as
 * leaves carrying size / modified / generated chips, replacing the old
 * single area-grouped list. The curated top-rank files
 * (importance_rules/<type>_<rank>_rank.json — importance ranks 0-1)
 * carry their code-count + first codes inline in the Path cell, parsed
 * from the JSON itself.
 *
 * Opening a file pops up SecStaticsDialog: the JSON as a plain item
 * table (item fields in table columns, containers of objects flatten to
 * one row per child — no expansion) with the raw-JSON hand-edit path
 * (Format / Reload / Save PUT) kept alongside.
 *
 * Data: GET/PUT /api/config/sec-statics[/file] (plain fetch — these
 * pages mutate the underlying files). rules + importance + owners are
 * hand-edited; catalog / index shards are regenerated wholesale by
 * builds.classification (chipped, so edits are known to be temporary).
 */
import { useCallback, useEffect, useMemo, useState } from "react";
import {
  Alert,
  Box,
  Chip,
  CircularProgress,
  IconButton,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  TextField,
  Tooltip,
  Typography,
} from "@mui/material";
import ExpandMore from "@mui/icons-material/ExpandMore";
import KeyboardArrowRight from "@mui/icons-material/KeyboardArrowRight";
import FolderOutlined from "@mui/icons-material/FolderOutlined";
import Refresh from "@mui/icons-material/Refresh";
import {
  fetchSecStaticsFiles,
  type SecStaticsFile,
} from "@/lib/api-client/config";
import { fmtDateTimeShanghai } from "@/shared/datetime";
import {
  expandedTableBodyCellSx,
  expandedTableContainerSx,
  expandedTableHeadCellSx,
} from "@/shared/styles/expanded-table-styles";
import {
  buildFilePathTree,
  filterFilePathTree,
  type SecStaticsDirNode,
  type SecStaticsFileNode,
  type SecStaticsTreeNode,
} from "./filePathTree";
import SecStaticsDialog from "./SecStaticsDialog";

function fmtBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  return `${(bytes / 1024).toFixed(1)} KB`;
}

function GeneratedChip() {
  return (
    <Tooltip title="Generated by builds.classification — edits survive only until the next build">
      <Chip size="small" variant="outlined" label="gen" sx={{ height: 18 }} />
    </Tooltip>
  );
}

export default function SecStaticsPage() {
  const [files, setFiles] = useState<SecStaticsFile[] | null>(null);
  const [listError, setListError] = useState<string | null>(null);
  const [search, setSearch] = useState("");
  /** Dir paths currently expanded — search overrides to all-open. */
  const [expandedDirs, setExpandedDirs] = useState<Set<string>>(new Set());
  /** Open dialog's file path; null = closed. */
  const [dialogPath, setDialogPath] = useState<string | null>(null);

  const loadList = useCallback(async () => {
    try {
      const resp = await fetchSecStaticsFiles();
      setFiles(resp.files);
      setListError(null);
      // First load: top two levels open (rules / owners / catalog visible,
      // the 20+ per-sector index dirs stay collapsed until expanded).
      setExpandedDirs((prev) => {
        if (prev.size > 0) return prev;
        const next = new Set<string>();
        for (const f of resp.files) {
          const segments = f.path.split("/");
          if (segments.length >= 2) next.add(segments[0]);
          if (segments.length >= 3) next.add(segments.slice(0, 2).join("/"));
        }
        return next;
      });
    } catch (e) {
      setListError(String(e));
    }
  }, []);

  useEffect(() => {
    loadList();
  }, [loadList]);

  const query = search.trim().toLowerCase();
  const searchActive = query !== "";

  const tree = useMemo(
    () => (files == null ? [] : buildFilePathTree(files)),
    [files],
  );
  const visibleTree = useMemo(
    () => (searchActive ? filterFilePathTree(tree, query) : tree),
    [tree, query, searchActive],
  );

  // Depth-tagged DFS flatten + collapsed-subtree skip — the same row model
  // the JSON table uses, one level up.
  const rows = useMemo(() => {
    const flat: SecStaticsTreeNode[] = [];
    const walk = (nodes: SecStaticsTreeNode[]) => {
      for (const node of nodes) {
        flat.push(node);
        if (node.kind === "dir") {
          walk(node.files);
          walk(node.children);
        }
      }
    };
    walk(visibleTree);
    const out: SecStaticsTreeNode[] = [];
    let hideBelowDepth: number | null = null;
    for (const node of flat) {
      if (hideBelowDepth != null) {
        if (node.depth > hideBelowDepth) continue;
        hideBelowDepth = null;
      }
      out.push(node);
      if (node.kind === "dir" && !searchActive && !expandedDirs.has(node.path)) {
        hideBelowDepth = node.depth;
      }
    }
    return out;
  }, [visibleTree, expandedDirs, searchActive]);

  const toggleDir = useCallback(
    (dirPath: string) => {
      setExpandedDirs((prev) => {
        const next = new Set(prev);
        if (next.has(dirPath)) next.delete(dirPath);
        else next.add(dirPath);
        return next;
      });
    },
    [],
  );

  return (
    <Box sx={{ display: "flex", flexDirection: "column", gap: 2 }}>
      <Box sx={{ display: "flex", alignItems: "center", gap: 2, flexWrap: "wrap" }}>
        <Typography variant="h6">Security Classification</Typography>
        <Typography variant="caption" color="text.secondary">
          {files != null
            ? `${files.length} JSON files by directory · rules + importance + owners are hand-edited; catalog / index shards are regenerated by builds.classification · source: database/sec_statics/`
            : "loading…"}
        </Typography>
        <Box sx={{ flexGrow: 1 }} />
        <TextField
          size="small"
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          placeholder="Filter by path…"
          sx={{ width: 260 }}
        />
        <Tooltip title="Rescan the tree from disk">
          <span>
            <IconButton size="small" aria-label="rescan" onClick={loadList}>
              <Refresh fontSize="small" />
            </IconButton>
          </span>
        </Tooltip>
      </Box>

      {listError && <Alert severity="error">{listError}</Alert>}

      {files == null && listError == null && (
        <CircularProgress size={20} sx={{ m: 4, mx: "auto" }} />
      )}

      {files != null && (
        <TableContainer sx={expandedTableContainerSx("68vh")}>
          <Table size="small" stickyHeader>
            <TableHead>
              <TableRow>
                <TableCell sx={expandedTableHeadCellSx}>Path</TableCell>
                <TableCell sx={{ ...expandedTableHeadCellSx, width: 90 }} align="right">
                  Files
                </TableCell>
                <TableCell sx={{ ...expandedTableHeadCellSx, width: 110 }} align="right">
                  Size
                </TableCell>
                <TableCell sx={{ ...expandedTableHeadCellSx, width: 190 }}>
                  Modified
                </TableCell>
              </TableRow>
            </TableHead>
            <TableBody>
              {rows.map((node) =>
                node.kind === "dir" ? (
                  <DirRow
                    key={node.path}
                    node={node}
                    open={searchActive || expandedDirs.has(node.path)}
                    onToggle={toggleDir}
                  />
                ) : (
                  <FileRow key={node.path} node={node} onOpen={setDialogPath} />
                ),
              )}
              {rows.length === 0 && (
                <TableRow>
                  <TableCell colSpan={4}>
                    <Typography variant="caption" color="text.secondary">
                      No file matches “{search.trim()}”
                    </Typography>
                  </TableCell>
                </TableRow>
              )}
            </TableBody>
          </Table>
        </TableContainer>
      )}

      <SecStaticsDialog
        path={dialogPath}
        onClose={() => setDialogPath(null)}
        onSaved={loadList}
      />
    </Box>
  );
}

function DirRow({
  node,
  open,
  onToggle,
}: {
  node: SecStaticsDirNode;
  open: boolean;
  onToggle: (dirPath: string) => void;
}) {
  return (
    <TableRow
      hover
      onClick={() => onToggle(node.path)}
      sx={{ cursor: "pointer", bgcolor: "action.hover" }}
    >
      <TableCell sx={{ ...expandedTableBodyCellSx, pl: 1 + node.depth * 2.5 }}>
        <Box sx={{ display: "flex", alignItems: "center" }}>
          {open ? (
            <ExpandMore fontSize="small" sx={{ mr: 0.5, color: "text.secondary" }} />
          ) : (
            <KeyboardArrowRight fontSize="small" sx={{ mr: 0.5, color: "text.secondary" }} />
          )}
          <FolderOutlined sx={{ mr: 0.75, fontSize: 16, color: "text.secondary" }} />
          <Typography component="span" variant="inherit" sx={{ fontFamily: "monospace", fontWeight: 600 }}>
            {node.name}/
          </Typography>
          {node.generated === true && <GeneratedChip />}
        </Box>
      </TableCell>
      <TableCell sx={{ ...expandedTableBodyCellSx, fontFamily: "monospace" }} align="right">
        {node.fileCount}
      </TableCell>
      <TableCell sx={{ ...expandedTableBodyCellSx, fontFamily: "monospace" }} align="right">
        {fmtBytes(node.sizeBytes)}
      </TableCell>
      <TableCell sx={expandedTableBodyCellSx}>
        {node.updatedAt !== "" ? fmtDateTimeShanghai(node.updatedAt) : "—"}
      </TableCell>
    </TableRow>
  );
}

function FileRow({
  node,
  onOpen,
}: {
  node: SecStaticsFileNode;
  onOpen: (path: string) => void;
}) {
  const f = node.file;
  return (
    <TableRow hover onClick={() => onOpen(node.path)} sx={{ cursor: "pointer" }}>
      <TableCell sx={{ ...expandedTableBodyCellSx, pl: 3.5 + node.depth * 2.5 }}>
        <Box sx={{ display: "flex", alignItems: "center", flexWrap: "wrap" }}>
          <Typography
            component="span"
            variant="inherit"
            sx={{
              fontFamily: "monospace",
              color: f.generated ? "text.secondary" : "text.primary",
            }}
          >
            {node.name}
          </Typography>
          {f.generated && <GeneratedChip />}
          {f.codesCount != null && (
            <Tooltip
              title={`Curated importance-rank code list parsed from this JSON — click the row to view/edit all ${f.codesCount} codes`}
              arrow
            >
              <Typography
                component="span"
                variant="inherit"
                color="text.secondary"
                sx={{
                  fontFamily: "monospace",
                  whiteSpace: "nowrap",
                  overflow: "hidden",
                  textOverflow: "ellipsis",
                  maxWidth: 520,
                }}
              >
                {" · "}
                {f.codesCount} codes · {(f.sampleCodes ?? []).join(" ")}
                {f.codesCount > (f.sampleCodes?.length ?? 0) &&
                  ` +${f.codesCount - (f.sampleCodes?.length ?? 0)}`}
              </Typography>
            </Tooltip>
          )}
        </Box>
      </TableCell>
      <TableCell sx={expandedTableBodyCellSx} align="right" />
      <TableCell sx={{ ...expandedTableBodyCellSx, fontFamily: "monospace" }} align="right">
        {fmtBytes(f.sizeBytes)}
      </TableCell>
      <TableCell sx={expandedTableBodyCellSx}>{fmtDateTimeShanghai(f.updatedAt)}</TableCell>
    </TableRow>
  );
}
