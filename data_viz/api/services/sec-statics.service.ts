/**
 * Security-classification statics service — read/write access to the JSON
 * tree under database/sec_statics/ (the Config page's Security
 * Classification tab).
 *
 *   classification_rules/    hand-edited rule configs (config.json,
 *                            industry.json, strategy.json) consumed by
 *                            builds.classification's rule matcher.
 *   importance_rules/        hand-edited curated top-rank code lists
 *                            (<sec_type>_<rank>_rank.json) — ranks 0-1 of
 *                            every sec_type for builds.classification.
 *                            importance (read via
 *                            database/sec_statics/importance_rules_store).
 *   sec_owners.json          hand-edited curated owner registry
 *                            ("Hand-editable cache loaded by
 *                            build_classification.py").
 *   sec_classification/      GENERATED by builds.classification
 *                            (classification_store.write_state rewrites
 *                            the whole shard tree each run): meta.json +
 *                            per-sector catalog shards (NN_<SECTOR>.json —
 *                            the NN_ prefix encodes catalog order) +
 *                            per-(sector, industry) index shards
 *                            ({code: entry} maps). Edits here survive
 *                            only until the next build — the tab shows a
 *                            generated marker on these files.
 *
 * Writes are per-file and verbatim: the PUT body's text is validated as
 * JSON (parse only — schema authority stays with the Python consumers)
 * and written atomically (temp sibling + rename, same as
 * static-config.service). Only files already present in the walk are
 * writable — the API never creates new files in this tree (shard names
 * encode catalog order / grouping, so file creation belongs to the
 * build, not the UI).
 */
import fs from "fs";
import path from "path";
import { renameOver } from "./static-config.service.js";

const SEC_STATICS_DIR = path.resolve(
  import.meta.dirname ?? __dirname,
  "..",
  "..",
  "..",
  "database",
  "sec_statics",
);

/** Which slice of the sec_statics tree a file belongs to — the UI's
 *  left-panel grouping. `generated` marks files wholesale-rewritten by
 *  builds.classification on every run. */
export type SecStaticsArea =
  | "rules"
  | "importance"
  | "owners"
  | "catalog"
  | "indices"
  | "meta";

export interface SecStaticsFile {
  /** Tree-relative POSIX path ("classification_rules/config.json") — the
   *  key the read/write endpoints take. */
  path: string;
  area: SecStaticsArea;
  /** Rebuilt wholesale by builds.classification — UI warns on edit. */
  generated: boolean;
  sizeBytes: number;
  updatedAt: string;
  /** importance_rules rank files only — curated code-list summary parsed
   *  from the file itself (never the DB): the path table shows these
   *  inline so ranks 0-1 are visible without opening the file. */
  codesCount?: number;
  sampleCodes?: string[];
}

function areaFor(relPath: string): SecStaticsArea {
  if (relPath === "sec_owners.json") return "owners";
  if (relPath.startsWith("classification_rules/")) return "rules";
  if (relPath.startsWith("importance_rules/")) return "importance";
  if (relPath === "sec_classification/meta.json") return "meta";
  if (relPath.startsWith("sec_classification/catalog/")) return "catalog";
  return "indices";
}

/** Curated code-list summary parsed from an importance_rules JSON —
 *  {codes:[…]} shape per importance_rules_store; null when the file is
 *  unreadable, malformed, or carries no codes. */
function importanceCodesInfo(abs: string): {
  codesCount: number;
  sampleCodes: string[];
} | null {
  try {
    const parsed: unknown = JSON.parse(fs.readFileSync(abs, "utf-8"));
    const raw = Array.isArray((parsed as { codes?: unknown[] }).codes)
      ? ((parsed as { codes: unknown[] }).codes as unknown[])
      : [];
    const codes = raw.filter(
      (c): c is string => typeof c === "string" && c.trim() !== "",
    ).map((c) => c.trim());
    if (codes.length === 0) return null;
    return { codesCount: codes.length, sampleCodes: codes.slice(0, 5) };
  } catch {
    return null;
  }
}

function walkJsonFiles(dir: string, out: string[]): void {
  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walkJsonFiles(p, out);
    else if (entry.isFile() && entry.name.endsWith(".json")) out.push(p);
  }
}

/** Resolve a tree-relative path to its absolute file, REJECTING anything
 *  outside the tree or non-.json (segment check first so `..` and
 *  absolute paths never reach the filesystem join). */
function resolveTreePath(relPath: string): string {
  const segments = relPath.split("/");
  if (
    relPath === "" ||
    path.isAbsolute(relPath) ||
    segments.some((s) => s === "" || s === "." || s === "..")
  ) {
    throw new Error(`unusable sec_statics path: ${relPath}`);
  }
  const file = path.join(SEC_STATICS_DIR, ...segments);
  if (!file.endsWith(".json")) {
    throw new Error(`not a JSON config path: ${relPath}`);
  }
  return file;
}

/** Every *.json file under database/sec_statics/ (the whole tree IS the
 *  editable surface — __pycache__ and the .py modules are filtered by
 *  extension), tree-relative paths sorted rules → importance → owners →
 *  the generated sec_classification shards. */
export function listSecStaticsFiles(): SecStaticsFile[] {
  const files: string[] = [];
  walkJsonFiles(SEC_STATICS_DIR, files);
  const AREA_ORDER: Record<SecStaticsArea, number> = {
    rules: 0,
    importance: 1,
    owners: 2,
    meta: 3,
    catalog: 4,
    indices: 5,
  };
  return files
    .map((file) => {
      const relPath = path.relative(SEC_STATICS_DIR, file).split(path.sep).join("/");
      const area = areaFor(relPath);
      const stat = fs.statSync(file);
      const codes =
        area === "importance" ? importanceCodesInfo(file) : undefined;
      return {
        path: relPath,
        area,
        generated: area !== "rules" && area !== "importance" && area !== "owners",
        sizeBytes: stat.size,
        updatedAt: stat.mtime.toISOString(),
        ...(codes ?? {}),
      };
    })
    .sort(
      (a, b) =>
        AREA_ORDER[a.area] - AREA_ORDER[b.area] || a.path.localeCompare(b.path),
    );
}

/** One file's raw text (the editor's verbatim content) + its inventory
 *  entry. */
export function readSecStaticsFile(relPath: string): {
  file: SecStaticsFile;
  text: string;
} {
  const file = resolveTreePath(relPath);
  const abs = path.resolve(file);
  const entries = listSecStaticsFiles();
  const entry = entries.find((e) => path.join(SEC_STATICS_DIR, e.path) === abs);
  if (entry == null) {
    throw new Error(`no such file in the sec_statics tree: ${relPath}`);
  }
  return { file: entry, text: fs.readFileSync(abs, "utf-8") };
}

/** Write one file's text verbatim after JSON-validating it. Returns the
 *  updated inventory entry (new mtime). */
export function writeSecStaticsFile(relPath: string, text: string): SecStaticsFile {
  const abs = resolveTreePath(relPath);
  if (!fs.existsSync(abs) || !fs.statSync(abs).isFile()) {
    throw new Error(`no such file in the sec_statics tree: ${relPath}`);
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch (err) {
    throw new Error(`invalid JSON — ${String(err)}`);
  }
  if (parsed == null || typeof parsed !== "object") {
    // Shards and rule configs are all objects/arrays; a bare scalar is
    // certainly a paste accident.
    throw new Error("invalid JSON — top-level value must be an object or array");
  }
  const tmp = `${abs}.tmp-${process.pid}`;
  // Verbatim write — the UI round-trips the exact text it loaded, so a
  // save that changed nothing produces no git diff (Python-written
  // shards carry no trailing newline; don't add one).
  fs.writeFileSync(tmp, text, "utf-8");
  try {
    renameOver(tmp, abs);
  } catch (err) {
    fs.rmSync(tmp, { force: true });
    throw err;
  }
  const entry = listSecStaticsFiles().find((e) => e.path === relPath);
  if (entry == null) {
    throw new Error(`post-write inventory miss for ${relPath}`);
  }
  return entry;
}
