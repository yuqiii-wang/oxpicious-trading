"""llm_agents.llm_qa_by_research.storage — DB layer for the research-logic Q&A base.

Persists curated question/answer documents into
``llm.llm_qa_by_research`` (canonical DDL:
database/sql/text/llm/04_llm_qa_by_research.sql) — the industry/security
LOGIC analog of ``llm.llm_qa``: same question/answer + news-group
provenance shape, but each row is generated by FIVE separate LLM
requests (see :mod:`llm_agents.llm_qa_by_research.generation`): five
evaluation dimensions — ``intro`` / ``optimistic_forecast`` /
``pessimistic_forecast`` / ``risks`` / ``capitalization`` — plus a 6th
SUMMARY request whose output lands in
``answer`` and which assigns the ``logic_label`` (a static.label_dim
SMALLINT code, domain ``research_logic``).

The write API is idempotent per (question, news_group):

  * ``upsert_qa_by_research`` — insert or update one row (+ optional group).
  * ``deactivate_qa_by_research`` — soft-delete (is_active = false).
  * ``fetch_qa_by_research`` — list active rows, optionally by
    industry/sector/logic-label code.
"""
from __future__ import annotations

