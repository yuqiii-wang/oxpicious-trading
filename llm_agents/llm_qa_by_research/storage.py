async def upsert_qa_by_research(
    conn,
    question: str,
    answer: str,
    logic_label: int,
    *,
    intro: Optional[str] = None,
    optimistic_forecast: Optional[str] = None,
    pessimistic_forecast: Optional[str] = None,
    risks: Optional[str] = None,
    capitalization: Optional[str] = None,
    context: Optional[str] = None,
    category: Optional[str] = None,
    industry_id: Optional[str] = None,
    sector_id: Optional[str] = None,
    news_ids: Optional[Sequence[int]] = None,
    request_ids: Optional[Sequence[int]] = None,
    dim_refs: Optional[str] = None,
    llm_model: Optional[str] = None,
    language: str = "zh",
    is_active: bool = True,
    qa_date: Optional[datetime.datetime] = None,
) -> int:
    """Insert/update one llm.llm_qa_by_research row; return its qa_id.

    *answer* is the 6th request's SUMMARY of the five dimension texts;
    *intro* / *optimistic_forecast* / *pessimistic_forecast* / *risks* /
    *capitalization* are the five dimension requests' answers —
    None when that dimension's request failed. *logic_label* is the
    static.label_dim
    research_logic CODE (an int in RESEARCH_LOGIC_LABEL; the DB column
    is SMALLINT); the CLI maps the label name to it.

    With *news_ids*, the sources are grouped (ensure_news_group, shared
    with llm.llm_qa) and linked — the generation flow passes the MERGED
    news rows of all five dimension requests' hits (the by-research refs
    mapping). Uniqueness is (question, news_group_id); because Postgres
    UNIQUE treats NULLs as distinct, the news-less case is matched
    explicitly on question + NULL group and updated in place. *qa_date*
    semantics identical to llm_agents.llm_qa.upsert_qa.

    is_failed_explanation is derived here from the answer text via
    FAILED_EXPLANATION_KEYWORDS (shared with llm.llm_qa): refusal
    boilerplate -> true; any substantive answer -> false.
    """
    if not question or not answer:
        raise ValueError("question and answer are required")
    if logic_label not in RESEARCH_LOGIC_LABEL:
        raise ValueError(
            f"logic_label must be a research_logic code in "
            f"{sorted(RESEARCH_LOGIC_LABEL)}, got {logic_label!r}")

    failed_explanation = any(k in answer
                             for k in FAILED_EXPLANATION_KEYWORDS)

    # Store-time caps (llm_agents._core.text_caps): the rendered answer +
    # dimension texts at the summary cap, the never-rendered context
    # passage at the context cap — after the refusal derivation.
    answer = truncate_summary(answer)
    intro = truncate_summary(intro)
    optimistic_forecast = truncate_summary(optimistic_forecast)
    pessimistic_forecast = truncate_summary(pessimistic_forecast)
    risks = truncate_summary(risks)
    capitalization = truncate_summary(capitalization)
    context = truncate_context(context)

    news_group_id: Optional[int] = None
    if news_ids:
        news_group_id = await ensure_news_group(
            conn, news_ids, name=f"qa-research: {question[:60]}")

    if news_group_id is None:
        qa_id = await conn.fetchval(
            f'SELECT qa_id FROM {QA_TABLE} '
            f'WHERE question = $1 AND news_group_id IS NULL',
            question)
        if qa_id is not None:
            await conn.execute(
                f'UPDATE {QA_TABLE} SET answer = $2, context = $3, '
                f'intro = $4, optimistic_forecast = $5, '
                f'pessimistic_forecast = $6, risks = $7, capitalization = $8, '
                f'logic_label = $9, '
                f'category = $10, industry_id = $11, sector_id = $12, '
                f'llm_model = $13, language = $14, is_active = $15, '
                f'qa_date = COALESCE($16::timestamptz, qa_date), '
                f'is_failed_explanation = $17, request_ids = $18, '
                f'dim_refs = $19::jsonb, '
                f'updated_at = now() '
                f'WHERE qa_id = $1',
                qa_id, answer, context, intro, optimistic_forecast,
                pessimistic_forecast, risks, capitalization,
                logic_label,
                category, industry_id, sector_id,
                llm_model, language, is_active, qa_date,
                failed_explanation, list(request_ids or []), dim_refs)
            await _refresh_research_search_tsv(
                conn, qa_id, question, answer, context,
                intro=intro, optimistic_forecast=optimistic_forecast,
                pessimistic_forecast=pessimistic_forecast, risks=risks,
                capitalization=capitalization)
            return qa_id

    row = {
        "question": question,
        "answer": answer,
        "context": context,
        "intro": intro,
        "optimistic_forecast": optimistic_forecast,
        "pessimistic_forecast": pessimistic_forecast,
        "risks": risks,
        "capitalization": capitalization,
        "logic_label": logic_label,
        "category": category,
        "industry_id": industry_id,
        "sector_id": sector_id,
        "news_group_id": news_group_id,
        "llm_model": llm_model,
        "request_ids": list(request_ids or []),
        "dim_refs": dim_refs,
        "language": language,
        "is_active": is_active,
        "is_failed_explanation": failed_explanation,
    }
    if qa_date is not None:
        row["qa_date"] = qa_date
    await bulk_upsert_async(conn, QA_TABLE, [row], ["question", "news_group_id"])
    qa_id = await conn.fetchval(
        f'SELECT qa_id FROM {QA_TABLE} '
        f'WHERE question = $1 AND news_group_id IS NOT DISTINCT FROM $2',
        question, news_group_id)
    await _refresh_research_search_tsv(
        conn, qa_id, question, answer, context,
        intro=intro, optimistic_forecast=optimistic_forecast,
        pessimistic_forecast=pessimistic_forecast, risks=risks,
        capitalization=capitalization)
    return qa_id


async def _refresh_research_search_tsv(
    conn, qa_id: Optional[int], question: str, answer: str,
    context: Optional[str], *, intro: Optional[str],
    optimistic_forecast: Optional[str],
    pessimistic_forecast: Optional[str], risks: Optional[str],
    capitalization: Optional[str],
) -> None:
    """search_tsv tail (TSV_SPECS): question A, answer B, the
    five dimension texts C, context D. Unconditional — the update path
    rewrites the texts, so the tsvector must follow them. Also refreshes
    the table's high-DF lexeme stats (text.search_lexicon_df — full
    replace, tiny for this table)."""
    if qa_id is None:
        return
    from _common.tokenization import SearchIndexer
    await SearchIndexer.get().set_search_tsv_async(conn, QA_TABLE, [{
        "qa_id": qa_id, "question": question, "answer": answer,
        "context": context, "intro": intro,
        "optimistic_forecast": optimistic_forecast,
        "pessimistic_forecast": pessimistic_forecast, "risks": risks,
        "capitalization": capitalization,
    }])
    await SearchIndexer.get().refresh_lexicon_df_async(conn, QA_TABLE)


# One season/quarter: the per-industry generation cooldown window (days).
# An industry whose newest ACTIVE research row is younger than this is
# skipped by default (cli generate without --force, and the ai_daily
# movers auto-run) — the row is still fresh enough to serve.
RESEARCH_COOLDOWN_DAYS = 91


async def industry_quarter_present(
    conn, industry_id: Optional[str],
    *, cooldown_days: int = RESEARCH_COOLDOWN_DAYS,
) -> Optional[datetime.datetime]:
    """The industry's newest ACTIVE research qa_date when it sits inside
    the quarterly cooldown window, else None.

    The cooldown gate of the auto-run paths: a present (industry, season)
    row means the research base already covers this quarter — skip. None
    *industry_id* (broad/unnamed subjects) never cooldowns. """
    if not industry_id:
        return None
    return await conn.fetchval(
        f'SELECT MAX(q.qa_date) FROM {QA_TABLE} q '
        f'WHERE q.is_active AND q.industry_id = $1 '
        f'  AND q.qa_date >= now() - make_interval(days => $2)',
        industry_id, cooldown_days)


async def set_has_refs(conn, qa_id: int, has_refs: bool) -> None:
    """Mirror the refs mapping into the row's has_refs flag (the store
    pattern of llm.llm_qa: the flag is set after the group write, true
    iff the linked news group carries items)."""
    await conn.execute(
        f'UPDATE {QA_TABLE} SET has_refs = $2, updated_at = now() '
        f'WHERE qa_id = $1', qa_id, has_refs)


async def deactivate_qa_by_research(conn, qa_id: int) -> bool:
    """Soft-delete: is_active = false. Returns True when a row matched."""
    status = await conn.execute(
        f'UPDATE {QA_TABLE} SET is_active = false, updated_at = now() '
        f'WHERE qa_id = $1', qa_id)
    return status == "UPDATE 1"


async def fetch_qa_by_research(
    conn,
    limit: int = 20,
    include_inactive: bool = False,
    industry_id: Optional[str] = None,
    sector_id: Optional[str] = None,
    logic_label: Optional[int] = None,
) -> List[dict]:
    """Newest-first research Q&A rows (joined with source-group count).

    *logic_label* filters on the stored research_logic CODE (None = all).
    """
    rows = await conn.fetch(
        f'SELECT q.qa_id, q.question, q.answer, q.intro, '
        f'q.optimistic_forecast, q.pessimistic_forecast, q.risks, '
        f'q.capitalization, q.logic_label, q.category, q.industry_id, '
        f'q.sector_id, '
        f'q.news_group_id, q.llm_model, q.language, q.is_active, '
        f'q.has_refs, q.is_failed_explanation, q.qa_date, q.updated_at, '
        f'(SELECT COUNT(*) FROM text.news_group_items gi '
        f' WHERE gi.news_group_id = q.news_group_id) AS n_sources '
        f'FROM {QA_TABLE} q '
        f'WHERE ($1 OR q.is_active) '
        f'  AND ($2::text IS NULL OR q.industry_id = $2) '
        f'  AND ($3::text IS NULL OR q.sector_id = $3) '
        f'  AND ($4::smallint IS NULL OR q.logic_label = $4) '
        f'ORDER BY q.updated_at DESC LIMIT $5',
        include_inactive, industry_id, sector_id, logic_label, limit)
    return [dict(r) for r in rows]
