-- ============================================================================
--  Table: analysis_forecasts.forecast_results
--
--  The RESULT data of the forecast analysis (motivation — the bucket
--  definitions — lives in analysis_forecasts.mov_rsi / mov_std, which
--  link here via forecast_id). One row per forecast bucket, keyed by the
--  surrogate forecast_id; there is no security/month information in this
--  table by design.
--
--  Columns (all over the bucket days of one trailing 5-year window):
--    ave_next_{n}       — MEAN n-day forward fractional change
--    max_{n} / min_{n}  — MAX / MIN n-day forward fractional change
--                         (close-based; 5d/20d/60d horizons only)
--    max_low_change_ratio_{n}
--                       — (1 + max change pct) / (1 + min change pct) =
--                         max(close[t+1..t+n]) / min(close[t+1..t+n]),
--                         the within-window close swing amplitude derived
--                         from the row's max/min forward changes
--                         (5d/20d/60d horizons only)
--    occurrence_count_{n} — number of bucket days with a VALID n-day
--                         forward change (the mean/probability denominator)
--    reverse_prob_{n}   — P(n-day change is a REVERSAL > 1% against the
--                         bucket side), over bucket days with a valid
--                         n-day forward change
--  with the horizon suffix _{n} ∈ {'' (next day), '5d', '20d', '60d'}
--  — e.g. ave_next_change (next day), ave_next_5d_change, max_5d_change,
--  max_low_change_ratio_20d, reverse_prob_60d. The next-day horizon has
--  no max/min/max_low_change_ratio columns.
--
--  Every aggregate is computed only over bucket days with a VALID
--  n-day forward change (the horizon denominator); a NULL column means
--  no bucket day had one (e.g. the code's history ends inside the
--  horizon). High/low are NULL when the denominator is 0.
-- ============================================================================

CREATE TABLE IF NOT EXISTS analysis_forecasts.forecast_results (
    forecast_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,

    -- mean forward changes (fractional ratios, e.g. 0.05 = +5%)
    ave_next_change    NUMERIC(10,6),
    ave_next_5d_change NUMERIC(10,6),
    ave_next_20d_change NUMERIC(10,6),
    ave_next_60d_change NUMERIC(10,6),

    -- max/min forward changes (close-based; 5d/20d/60d horizons only —
    -- the next-day horizon has none)
    max_5d_change NUMERIC(10,6),
    max_20d_change NUMERIC(10,6),
    max_60d_change NUMERIC(10,6),
    min_5d_change NUMERIC(10,6),
    min_20d_change NUMERIC(10,6),
    min_60d_change NUMERIC(10,6),

    occurrence_count_next BIGINT,
    occurrence_count_5d BIGINT,
    occurrence_count_20d BIGINT,
    occurrence_count_60d BIGINT,

    -- within-window close swing amplitude: (1 + max change pct) /
    -- (1 + min change pct) = max(close) / min(close) over close[t+1..t+n],
    -- derived from the row's max/min changes; 5d/20d/60d only
    max_low_change_ratio_5d NUMERIC(10,6),
    max_low_change_ratio_20d NUMERIC(10,6),
    max_low_change_ratio_60d NUMERIC(10,6),

    -- P(forward change reverses > 1% against the bucket side)
    -- NUMERIC(8,6): probability ∈ [0,1] but exactly 1.0 must fit —
    -- NUMERIC(6,6) (scale 6 ⇒ |v| < 1) would overflow on all-reverse
    -- buckets, which are common at the 5d/20d/60d horizons.
    reverse_prob        NUMERIC(8,6),
    reverse_prob_5d     NUMERIC(8,6),
    reverse_prob_20d    NUMERIC(8,6),
    reverse_prob_60d    NUMERIC(8,6),

    CONSTRAINT pk_forecast_results PRIMARY KEY (forecast_id)
) PARTITION BY HASH (forecast_id);

-- Native hash partitions (16) keyed by forecast_id — created via the
-- shared util (database/sql/00_partition_utils.sql); children are named
-- _p00.._p15
SELECT public.create_hash_partitions('analysis_forecasts', 'forecast_results', 16);

