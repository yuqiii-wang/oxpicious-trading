-- ============================================================================
--  Analysis Advice
--  analysis.analysis_advice — the ANALYSIS-WIDE shared advice store behind
--  the UI "Analysis Advice" component (the "A" icon beside the population
--  toggle strip): for one analysis item scoped to a sec_type / industry /
--  code, the concise text of what a SIGNIFICANT vs INSIGNIFICANT result
--  means in this system's own terms (the gate, the sample floors, the
--  significance bars), its trading implications, and the DYNAMIC
--  justification tables (data-derived snapshots that ground the text).
--
--  Scope resolution: the PK is a 6-part NATURAL TEXT key — every scope
--  component not applicable to a row is stored as '' (never NULL), so the
--  key space is flat and lookups fall back from code-specific to
--  scope-generic advice by matching (code, '') / (industry, '') pairs and
--  ordering by specificity (code <> '' DESC, industry <> '' DESC). The
--  topic slot lets ONE analysis item carry SEVERAL advice rows (one per
--  sub-topic — '' = the item's default/main advice).
--
--  The keyword1/2/3 columns are the KEYWORD INDEX slots — up to three
--  free-text search tags per row (lookups match a query against ANY slot),
--  each carrying its own btree index; '' = the slot is unused.
--
--  The service_name column scopes a row to the pipeline SERVICE it
--  explains (the Python package name, e.g. 'analysis_signals') with its
--  own btree index for service-scoped lookups; '' = not service-scoped.
--
--  The text columns are deliberately TEXT (the static.label_dim NOT-
--  converted list: API-facing identity + filter columns) — this is a
--  documentation-shaped config table, not a cudf frame payload.
--
--  Idempotent and NON-destructive: CREATE IF NOT EXISTS + IF NOT EXISTS
--  indexes/ALTERs + a drop-and-re-add PK rebuild (advice rows are
--  seed-maintained, never pipeline-purged), so re-running the file against
--  a populated DB is safe.
-- ============================================================================

CREATE TABLE IF NOT EXISTS analysis.analysis_advice (
    analysis_item TEXT  NOT NULL,               -- the analysis item the advice explains — an open vocabulary: the signal families ('mov_rsi' / 'bollinger' / 'ma_cross' — the UI Signal picker values), later any analysis item name
    topic         TEXT  NOT NULL DEFAULT '',    -- the sub-topic of the advice within the analysis item — an open vocabulary ('' = the item's default/main advice; two rows of one item differ by topic)
    sec_type      TEXT  NOT NULL DEFAULT '',    -- 'etf' / 'index' / 'stock'; '' = every sec type
    industry      TEXT  NOT NULL DEFAULT '',    -- stats.sec_classification.industry_id scope ('BROAD_SSE', 'BANKS', ...); '' = unscoped
    code          TEXT  NOT NULL DEFAULT '',    -- the security's ticker in the owning tables' convention (indices/ETFs bare '000001', stocks suffixed '600008.SS'); '' = scope-wide advice
    custom_text   TEXT  NOT NULL DEFAULT '',    -- optional free-text disambiguator for two advices that share the rest of the key; '' = none

    service_name  TEXT  NOT NULL DEFAULT '',    -- the pipeline SERVICE the advice explains ('analysis_signals', ... — the Python package names); '' = not service-scoped
    keyword1      TEXT  NOT NULL DEFAULT '',    -- keyword index slot 1 — free-text search tag; '' = unused
    keyword2      TEXT  NOT NULL DEFAULT '',    -- keyword index slot 2 — free-text search tag; '' = unused
    keyword3      TEXT  NOT NULL DEFAULT '',    -- keyword index slot 3 — free-text search tag; '' = unused

    as_of_date    DATE  NOT NULL,               -- BY WHICH DATA DATE the row was generated (the underlying signals' latest snapshot end_date the justification tables snapshot) — the freshness stamp consumers display

    significance  JSONB NOT NULL DEFAULT '{}'::jsonb,   -- the WHAT-IT-MEANS text bundle: {"significant": str, "insignificant": str, "basis": str} — extra str keys render as their own labeled paragraphs
    implications  JSONB NOT NULL DEFAULT '[]'::jsonb,   -- the trading implications: [{"title": str, "text": str}] (plain strings allowed — rendered as untitled bullets)
    justification JSONB NOT NULL DEFAULT '[]'::jsonb,   -- the DYNAMIC tables grounding the advice: [{"title": str, "note": str?, "columns": [{"key","label","align"?,"mono"?}], "rows": [[cell, ...], ...]}] — cells are str | number | null (null renders as '—'); regenerated by the seed script from live data
    meta          JSONB NOT NULL DEFAULT '{}'::jsonb,   -- provenance, free-form: {"generated_by", "sources": [table, ...], data coverage dates, ...}

    CONSTRAINT pk_analysis_advice PRIMARY KEY (analysis_item, topic, sec_type, industry, code, custom_text)
);

-- ----------------------------------------------------------------------------
--  Retro-fit for deployments whose analysis.analysis_advice predates the
--  topic / service_name / keyword columns (the CREATE above already includes
--  them for fresh installs). Existing rows take the defaults ('' — the
--  item's main advice, not service-scoped, keyword slots unused), so the
--  widened PK stays unique.
-- ----------------------------------------------------------------------------
ALTER TABLE analysis.analysis_advice
    ADD COLUMN IF NOT EXISTS topic        TEXT NOT NULL DEFAULT '';
ALTER TABLE analysis.analysis_advice
    ADD COLUMN IF NOT EXISTS service_name TEXT NOT NULL DEFAULT '';
ALTER TABLE analysis.analysis_advice
    ADD COLUMN IF NOT EXISTS keyword1     TEXT NOT NULL DEFAULT '';
ALTER TABLE analysis.analysis_advice
    ADD COLUMN IF NOT EXISTS keyword2 TEXT NOT NULL DEFAULT '';
ALTER TABLE analysis.analysis_advice
    ADD COLUMN IF NOT EXISTS keyword3 TEXT NOT NULL DEFAULT '';

-- PK rebuild onto the widened 6-part key (drop-and-re-add: harmless on a
-- table already carrying the 6-part form — widening a unique key can never
-- collide).
ALTER TABLE analysis.analysis_advice
    DROP CONSTRAINT IF EXISTS pk_analysis_advice;
ALTER TABLE analysis.analysis_advice
    ADD CONSTRAINT pk_analysis_advice
    PRIMARY KEY (analysis_item, topic, sec_type, industry, code, custom_text);

-- ----------------------------------------------------------------------------
--  Indexes
-- ----------------------------------------------------------------------------
-- Security-scoped lookups without the analysis item (all advice available
-- for one (sec_type, industry, code) — the component's context resolve).
CREATE INDEX IF NOT EXISTS idx_analysis_advice_scope
    ON analysis.analysis_advice (sec_type, industry, code);

-- Freshness queries (latest as_of_date — cache versioning, staleness checks).
CREATE INDEX IF NOT EXISTS idx_analysis_advice_as_of_date
    ON analysis.analysis_advice (as_of_date);

-- Service-scoped lookups: every advice row of one pipeline service.
CREATE INDEX IF NOT EXISTS idx_analysis_advice_service_name
    ON analysis.analysis_advice (service_name);

-- Keyword lookups: a query tag matches ANY of the three slots, so each slot
-- carries its own btree index (WHERE keyword1 = $k OR keyword2 = $k OR ...).
CREATE INDEX IF NOT EXISTS idx_analysis_advice_keyword1
    ON analysis.analysis_advice (keyword1);
CREATE INDEX IF NOT EXISTS idx_analysis_advice_keyword2
    ON analysis.analysis_advice (keyword2);
CREATE INDEX IF NOT EXISTS idx_analysis_advice_keyword3
    ON analysis.analysis_advice (keyword3);

