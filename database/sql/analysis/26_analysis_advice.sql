COMMENT ON COLUMN analysis.analysis_advice.analysis_item IS 'The analysis item the advice explains — an OPEN vocabulary (not a label_dim domain): the signal families first (''mov_rsi'' / ''bollinger'' / ''ma_cross'' — exactly the UI Signal picker values / SIGNAL_TYPE_LABELS keys), later any analysis item name. Leading PK member: lookups always carry the item.';
