COMMENT ON COLUMN analysis.analysis_advice.implications IS 'The trading implications as a jsonb array of {"title": str, "text": str} (untitled plain strings allowed) — what a significant / insignificant reading implies for reading the signals (confidence units, pass populations, regime splits), concise one-to-two-sentence entries.';
