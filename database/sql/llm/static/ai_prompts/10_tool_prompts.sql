-- ============================================================================
--  AI prompts seed — prompt_type 4 tool: one row per model-callable
--  tool, its DESCRIPTION as DB-editable text.
--  Table: llm.ai_prompts (DDL + the shared contract: 06_ai_prompts.sql;
--  sibling static files 01..09 — one per prompt category).
--
--  The deep agent's tool schemas lived only in the Python tool classes
--  (llm_agents/deep_agents/tools — the Tool subclasses'
--  DEFAULT_DESCRIPTION constants); this seed migrates the descriptions
--  into llm.ai_prompts so they are editable without a code change.
--  Resolution at run start (runner.run_thread -> fetch_tool_prompts,
--  applied by the tool kits at mount time — tools.base's override
--  contract): the ACTIVE row's instruction (joined by
--  prompt_key|prompt_sub_type — a tool's db_key) wins; a missing key,
--  a deactivated row, or a DB outage falls back to the built-in
--  constant — fail-soft, a run never dies over prompt management.
--
--  prompt_sub_type groups the rows by the tool's kit/domain (an
--  open-ended TEXT vocabulary, no label_dim mirror): sandbox = the
--  docker py-sandbox tools, delegation = the loop's spawn/collect,
--  plan_main / plan_fork = the plan-mutation tools' MAIN / fork
--  variants (the SAME tool name carries two authority-narrowed
--  schemas), plan = the thread-internal search, stats = the stats_*
--  study tools, mcp = the read-only DB
--  MCP server's tools (CATALOG rows only — the MCP server owns those
--  live schemas; the rows document them in this registry).
--
--  SEEDED FROM the tool classes (dollar-quoted $txt$ blocks — no
--  escaping): tools.sandbox_tools / tools.delegation_tools /
--  tools.plan_tools / tools.thread_search / tools.stats_tools /
--  tools.prompt_tools / tools.kg_tools DEFAULT_DESCRIPTION constants,
--  plus llm_agents/mcp/readonly_server.py's tool docstrings for the
--  mcp rows. Keep the seed and the constants in sync —
--  temp_scripts/check_tool_prompts.py asserts it.
--
--  Idempotent — re-running refreshes the seeded texts in place. The
--  version column stays at its seeded 1 and is deliberately NOT in the
--  ON CONFLICT SET: a re-run never resets a manually bumped version
--  (the UI edit path bumps it).
-- ============================================================================

